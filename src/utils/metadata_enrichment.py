"""
Metadata enrichment utility.

This module loads the parsed flu metadata table and attaches it, per isolate, to any
record frame keyed by `assembly_id` (hn_subtype, host, year) for metadata filtering.

Note: flu_genomes_metadata_parsed.csv is generated by flu_genomes_eda.py script.
"""

from pathlib import Path
from typing import Optional

import pandas as pd


def load_flu_metadata(
    metadata_file: Optional[Path] = None,
    project_root: Optional[Path] = None) -> pd.DataFrame:
    """
    Load flu metadata from processed CSV file.
    
    Args:
        metadata_file: Path to metadata CSV file. If None, uses default location.
        project_root: Project root directory. If None, infers from file location.
    
    Returns:
        DataFrame with columns: assembly_id, host, year, hn_subtype, ...
    """
    if metadata_file is None:
        if project_root is None:
            # Infer project root from this file's location
            project_root = Path(__file__).resolve().parents[2]
        metadata_file = project_root / "data" / "processed" / "flu" / "metadata_eda" / "flu_genomes_metadata_parsed.csv"

    if not metadata_file.exists():
        raise FileNotFoundError(f"Metadata file not found: {metadata_file}")

    meta = pd.read_csv(metadata_file)

    # Upstream key is `hash_id`; the rest of the pipeline keys on `assembly_id` (same value).
    meta = meta.rename(columns={'hash_id': 'assembly_id'})
    meta['assembly_id'] = meta['assembly_id'].astype(str)

    # Cast types: year to int, hn_subtype and host to str
    if 'year' in meta.columns:
        # Convert to numeric first (handles strings), then to Int64 (nullable integer type)
        meta['year'] = pd.to_numeric(meta['year'], errors='coerce').astype('Int64')
    if 'hn_subtype' in meta.columns:
        meta['hn_subtype'] = meta['hn_subtype'].astype(str)
        meta['hn_subtype'] = meta['hn_subtype'].replace('nan', pd.NA) # Replace 'nan' str with actual NaN
    if 'host' in meta.columns:
        meta['host'] = meta['host'].astype(str)
        meta['host'] = meta['host'].replace('nan', pd.NA) # Replace 'nan' str with actual NaN

    return meta


def attach_isolate_metadata(
    df: pd.DataFrame,
    metadata_file: Optional[Path] = None,
    project_root: Optional[Path] = None
    ) -> pd.DataFrame:
    """Left-join per-isolate metadata (hn_subtype, host, year, ...) onto records by assembly_id.

    `assembly_id` is the only column required of `df`, so protein, CDS DNA and contig DNA
    frames are all accepted.

    Args:
        df: DataFrame with an 'assembly_id' column.
        metadata_file: Path to metadata CSV file. If None, uses default location.
        project_root: Project root directory. If None, infers from file location.

    Returns:
        `df` with hn_subtype, host and year added, plus geo_location_clean and passage
        when the metadata file carries them.
    """
    # TODO: near-duplicate of build_cluster_membership.attach_metadata -- same load_flu_metadata
    # + assembly_id left-join, differing only in post-join policy (that one casts assembly_id to
    # str on both sides, dedups the metadata, fills categoricals with 'unknown' and returns a
    # match rate). Worth reconciling into one join primitive plus per-caller policy later.
    meta = load_flu_metadata(metadata_file, project_root)

    required_meta_cols = ['hn_subtype', 'host', 'year']
    meta_cols = ['assembly_id'] + required_meta_cols
    if 'geo_location_clean' in meta.columns:
        meta_cols.append('geo_location_clean')
    if 'passage' in meta.columns:
        meta_cols.append('passage')

    enriched_df = df.merge(meta[meta_cols], on='assembly_id', how='left')

    n_missing = enriched_df[required_meta_cols].isnull().any(axis=1).sum()
    n_total = len(enriched_df)
    if n_missing > 0:
        print(f"WARNING: {n_missing:,} out of {n_total:,} records ({100*n_missing/n_total:.1f}%) "
              f"have missing at least one of the required metadata: {required_meta_cols}.")

    return enriched_df


def filter_by_metadata(
    df: pd.DataFrame,
    hn_subtype=None,
    host=None,
    year=None,
    year_range=None,
    geo_location=None,
    passage=None,
    ) -> pd.DataFrame:
    """Filter records by isolate-level metadata criteria.

    Filtering is performed at the isolate level: isolates matching ALL specified
    criteria are identified, then ALL records from those isolates are
    kept. This ensures we don't lose records due to metadata merge issues
    (e.g., an isolate has host metadata on one protein but not another).

    Each axis parameter accepts:
      - None: no constraint on that axis (default).
      - scalar (str/int): exact match.
      - list / tuple: **set membership** (any length, including 1-element
        ``[2020]``). Length-based semantics are deliberately rejected -- a
        2-element list is always a set, never a range, to avoid surprises.

    ``year_range`` (year-axis only) accepts a 2-element ``[min, max]`` list
    for inclusive-range matching; mutually exclusive with ``year``. There is
    no ``host_range`` / ``hn_subtype_range`` / etc. -- those axes are not
    ordered. Pass a list for set membership instead.

    Raises ValueError on: ``year`` and ``year_range`` both set; malformed
    ``year_range``; empty list; geo_location / passage filter requested but
    the corresponding column is missing from ``df``.
    """
    if year is not None and year_range is not None:
        raise ValueError(
            "filter_by_metadata: 'year' and 'year_range' are mutually exclusive."
        )

    year_min, year_max = None, None
    if year_range is not None:
        if not isinstance(year_range, (list, tuple)) or len(year_range) != 2:
            raise ValueError(
                f"filter_by_metadata: year_range must be a 2-element [min, max] "
                f"list; got {year_range!r}."
            )
        try:
            year_min = int(year_range[0])
            year_max = int(year_range[1])
        except (TypeError, ValueError):
            raise ValueError(
                f"filter_by_metadata: year_range elements must be ints; "
                f"got {year_range!r}."
            )
        if year_min > year_max:
            raise ValueError(
                f"filter_by_metadata: year_range min ({year_min}) is greater "
                f"than max ({year_max})."
            )

    def _to_list(value, axis: str, coerce_int: bool = False):
        """Normalize scalar -> [scalar], pass through list/tuple as list.

        Empty lists are rejected (probably a config typo: an empty filter
        means "match nothing" which is never what a user wants). When
        ``coerce_int`` is set, all entries are int-coerced (year semantics).
        """
        if value is None:
            return None
        if isinstance(value, (list, tuple)):
            items = list(value)
        else:
            items = [value]
        if len(items) == 0:
            raise ValueError(
                f"filter_by_metadata: {axis} list cannot be empty."
            )
        if coerce_int:
            try:
                items = [int(v) for v in items]
            except (TypeError, ValueError):
                raise ValueError(
                    f"filter_by_metadata: {axis} values must be ints; got {value!r}."
                )
        return items

    hn_set = _to_list(hn_subtype, 'hn_subtype')
    host_set = _to_list(host, 'host')
    year_set = _to_list(year, 'year', coerce_int=True)
    geo_set = _to_list(geo_location, 'geo_location')
    passage_set = _to_list(passage, 'passage')

    any_filter = any(v is not None for v in
                     [hn_set, host_set, year_set, year_range, geo_set, passage_set])
    if not any_filter:
        return df

    year_disp = year_set if year_set is not None else (
        f"[{year_min}..{year_max}]" if year_range is not None else None)
    print('\nMetadata filtering enabled.')
    print(f'  hn_subtype:   {hn_set}')
    print(f'  host:         {host_set}')
    print(f'  year:         {year_disp}')
    print(f'  geo_location: {geo_set}')
    print(f'  passage:      {passage_set}')

    meta_cols = ['assembly_id', 'hn_subtype', 'host', 'year']
    if 'geo_location_clean' in df.columns:
        meta_cols.append('geo_location_clean')
    if 'passage' in df.columns:
        meta_cols.append('passage')
    aid_meta = df.groupby('assembly_id')[meta_cols].first().reset_index(drop=True)

    aid_mask = pd.Series([True] * len(aid_meta))

    if host_set is not None:
        before = aid_mask.sum()
        aid_mask = aid_mask & aid_meta['host'].isin(host_set)
        print(f"   host {host_set}: {before:,} -> {aid_mask.sum():,} isolates")

    if year_set is not None:
        before = aid_mask.sum()
        aid_mask = aid_mask & aid_meta['year'].isin(year_set)
        print(f"   year {year_set}: {before:,} -> {aid_mask.sum():,} isolates")
    elif year_range is not None:
        before = aid_mask.sum()
        aid_mask = aid_mask & aid_meta['year'].between(year_min, year_max, inclusive='both')
        print(f"   year [{year_min}..{year_max}]: {before:,} -> {aid_mask.sum():,} isolates")

    if hn_set is not None:
        before = aid_mask.sum()
        aid_mask = aid_mask & aid_meta['hn_subtype'].isin(hn_set)
        print(f"   hn_subtype {hn_set}: {before:,} -> {aid_mask.sum():,} isolates")

    if geo_set is not None:
        if 'geo_location_clean' not in aid_meta.columns:
            raise ValueError(
                "filter_by_metadata: geo_location filter requested but "
                "'geo_location_clean' column is missing from df."
            )
        before = aid_mask.sum()
        aid_mask = aid_mask & aid_meta['geo_location_clean'].isin(geo_set)
        print(f"   geo_location {geo_set}: {before:,} -> {aid_mask.sum():,} isolates")

    if passage_set is not None:
        if 'passage' not in aid_meta.columns:
            raise ValueError(
                "filter_by_metadata: passage filter requested but "
                "'passage' column is missing from df."
            )
        before = aid_mask.sum()
        aid_mask = aid_mask & aid_meta['passage'].isin(passage_set)
        print(f"   passage {passage_set}: {before:,} -> {aid_mask.sum():,} isolates")

    matching_isolates = aid_meta[aid_mask]['assembly_id'].tolist()
    n_before = len(df)
    df = df[df['assembly_id'].isin(matching_isolates)].reset_index(drop=True)
    n_after = len(df)

    print(f"   Filtered to {len(matching_isolates):,} isolates matching criteria")
    print(f"   Records: {n_before:,} -> {n_after:,} ({100*n_after/n_before:.1f}%)")

    return df
